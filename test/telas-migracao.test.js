// NEXA Telas: migração aditiva das tabelas que JÁ ESTÃO no ar (server/db/schema-telas.js TELAS_ADDED_COLS; docs/TELAS.md).
// A 0.5.188 criou telas_missing, telas_office_users e telas_alert_info; depois dela telas_missing ganhou colunas (o QR code
// de contato e a cartela policial). O CREATE TABLE IF NOT EXISTS não muda tabela que já existe: aqui o banco nasce com o
// esquema EXATO daquela versão (o SQL abaixo é o do commit 2d254843), com uma linha em cada tabela, o esquema atual sobe
// por cima e as colunas novas aparecem, as linhas antigas continuam e as rotas funcionam com elas. Nos dois bancos.
import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { boot, cleanup, api } from './helpers/srv.js';

const { TELAS_ADDED_COLS, telasPgMigrate, telasDDL } = await import('../server/db/schema-telas.js');

/** telas_missing como a 0.5.188 (commit 2d254843) a criou: sem qr_mode, qr_data, qr_label, header e warrant_no. */
const missing0588 = (d) => {
  const id = d === 'pg' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'; const big = d === 'pg' ? 'BIGINT' : 'INTEGER';
  return `CREATE TABLE telas_missing (
  id            ${id},
  tenant_id     ${big} NOT NULL,
  office_id     ${big},
  kind          TEXT NOT NULL DEFAULT 'adulto',
  name          TEXT NOT NULL,
  age           INTEGER,
  since         TEXT,
  last_seen     TEXT NOT NULL DEFAULT '',
  description   TEXT NOT NULL DEFAULT '',
  contact       TEXT NOT NULL DEFAULT '',
  photo_file    TEXT,
  photo_sha     TEXT,
  photo_bytes   ${big} NOT NULL DEFAULT 0,
  show_mode     TEXT NOT NULL DEFAULT 'both',
  full_sec      INTEGER NOT NULL DEFAULT 15,
  banner_sec    INTEGER NOT NULL DEFAULT 20,
  every_min     INTEGER NOT NULL DEFAULT 10,
  scope         TEXT NOT NULL,
  scope_data    TEXT NOT NULL DEFAULT '{}',
  until_at      ${big} NOT NULL,
  status        TEXT NOT NULL DEFAULT 'active',
  close_reason  TEXT,
  report_no     TEXT NOT NULL DEFAULT '',
  auth_name     TEXT NOT NULL DEFAULT '',
  auth_relation TEXT NOT NULL DEFAULT '',
  auth_ok       INTEGER NOT NULL DEFAULT 0,
  created_by    TEXT NOT NULL DEFAULT '',
  created_at    ${big} NOT NULL,
  updated_at    ${big},
  closed_by     TEXT,
  closed_at     ${big}
);
CREATE INDEX IF NOT EXISTS idx_telas_missing_tenant ON telas_missing(tenant_id, status, until_at);`;
};
const NEW_COLS = ['qr_mode', 'qr_data', 'qr_label', 'header', 'warrant_no'];
const OLD_ROW = (until, at) => `INSERT INTO telas_missing(tenant_id,office_id,kind,name,age,since,last_seen,description,contact,scope,scope_data,until_at,status,report_no,auth_name,auth_relation,auth_ok,created_by,created_at)
  VALUES(1,NULL,'crianca','Caso Antigo de Teste',9,'2026-11-01','Praca de teste','Blusa azul','Ligue 199 ou 190','city','{}',${until},'active','BO ANTIGO 1/2026','Responsavel de teste','familiar',1,'admin',${at})`;

test('migração: as colunas novas das tabelas que já estão no ar entram como ADD COLUMN, nunca só no CREATE TABLE', () => {
  // telas_offices ganhou o link e a senha cifrados e o alcance dos alertas (test/reparticoes-assistente-servidor.test.js)
  assert.deepEqual(TELAS_ADDED_COLS.map(([t, c]) => `${t}.${c}`), [...NEW_COLS.map((c) => `telas_missing.${c}`), 'telas_offices.link_enc', 'telas_offices.pass_enc', 'telas_offices.alert_reach', 'telas_devices.internal', 'telas_devices.sector_id',
    'telas_devices.hwid_hash', 'telas_devices.recovered_at']); // a licença que sobrevive à reinstalação (test/telas-licenca-reinstalar.test.js)
  for (const [t, c, lite, pg] of TELAS_ADDED_COLS) {
    assert.match(telasPgMigrate, new RegExp(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${c} `));
    // compatível com as linhas que já existem: NULL, ou NOT NULL com padrão
    for (const def of [lite, pg]) assert.ok(!/NOT NULL/.test(def) || /NOT NULL DEFAULT /.test(def), `${t}.${c}: ${def}`);
    for (const d of ['sqlite', 'pg']) assert.match(telasDDL(d), new RegExp(`\\n  ${c}\\s`), 'e no CREATE TABLE do banco novo');
  }
  // o esquema daquela versão é o de agora menos as colunas novas: nenhuma coluna de antes mudou de tipo nem de NOT NULL
  for (const d of ['sqlite', 'pg']) {
    const now = /CREATE TABLE IF NOT EXISTS telas_missing \(([\s\S]*?)\n\);/.exec(telasDDL(d))[1].split('\n').map((l) => l.trim().replace(/\s+/g, ' ').replace(/,$/, '')).filter(Boolean);
    const old = /CREATE TABLE telas_missing \(([\s\S]*?)\n\);/.exec(missing0588(d))[1].split('\n').map((l) => l.trim().replace(/\s+/g, ' ').replace(/,$/, '')).filter(Boolean);
    assert.deepEqual(now.filter((l) => !NEW_COLS.includes(l.split(' ')[0])), old, `${d}: as colunas de antes, iguais`);
  }
});

/** O que vale depois da migração: as linhas antigas continuam e as rotas funcionam com elas. */
async function confere(s, { ubsId, userLogin, alertId }) {
  const anon = api(s.base);
  const A = api(s.base, (await anon('POST', '/api/admin/login', { password: 'senha-inicial-longa' })).data.token);
  const bearer = (token) => (m, u, b) => anon(m, u, b, { authorization: `Bearer ${token}` });
  // o caso antigo aparece (sem QR próprio: o padrão), e as tabelas vizinhas seguem inteiras
  const lst = await A('GET', '/api/prefeitura/missing');
  assert.equal(lst.status, 200, JSON.stringify(lst.data));
  const old = lst.data.active.find((m) => m.name === 'Caso Antigo de Teste');
  assert.ok(old, 'o caso de antes continua lá');
  assert.deepEqual([old.kind, old.age, old.reportNo, old.authName, old.qr, old.header, old.warrantNo, old.hasPhoto], ['crianca', 9, 'BO ANTIGO 1/2026', 'Responsavel de teste', { mode: 'default', data: null, label: null }, null, null, false]);
  assert.deepEqual((await A('GET', `/api/prefeitura/offices/${ubsId}/users`)).data.users.map((u) => u.username), ['gestor.antigo'], 'o usuário de antes continua');
  const in1 = await anon('POST', '/api/reparticao/login', userLogin);
  assert.equal(in1.status, 200, 'e entra com a senha de antes');
  assert.equal((await A('GET', `/api/prefeitura/alerts/${alertId}`)).data.header, 'ALERTA SEVERO · PREFEITURA', 'a linha do tipo do alerta de antes continua');
  // vai às telas como antes (sem o campo qr), ganha o QR padrão, um QR só dele, edição e renovação
  const k = await A('POST', '/api/prefeitura/keys', { officeId: ubsId, name: 'Tela nova' });
  const T = bearer((await anon('POST', '/api/telas/activate', { key: k.data.key, device: { model: 'TV Box de teste' } })).data.token);
  const hb = async () => (await T('POST', '/api/telas/heartbeat', { rev: 'x', state: 'playing', source: 'hls', appVersion: '1.2.0', uptimeSec: 60, net: 'wifi', lastError: null, locked: true })).data;
  const item = (await hb()).missing.find((m) => m.name === 'Caso Antigo de Teste');
  assert.deepEqual(Object.keys(item).sort(), ['age', 'bannerSec', 'contact', 'description', 'everyMin', 'fullSec', 'id', 'kind', 'lastSeen', 'name', 'photo', 'show', 'since', 'until'], 'o caso antigo sai como saía');
  assert.equal((await A('PUT', '/api/prefeitura/missing/qr', { qr: { kind: 'tel', value: '552133330000' } })).status, 200);
  assert.deepEqual((await hb()).missing.find((m) => m.id === old.id).qr, { data: 'tel:+552133330000', label: 'Aponte a câmera e fale agora' });
  assert.equal((await A('PATCH', `/api/prefeitura/missing/${old.id}`, { description: 'Blusa azul e boné', days: 10, qr: { mode: 'custom', kind: 'whatsapp', value: '5521999990000' } })).status, 200);
  const again = (await hb()).missing.find((m) => m.id === old.id);
  assert.deepEqual([again.description, again.qr.data], ['Blusa azul e boné', 'https://wa.me/5521999990000']);
  // um caso novo convive com o antigo, e o antigo pode ser encerrado
  const novo = await A('POST', '/api/prefeitura/missing', { kind: 'idoso', name: 'Caso Novo de Teste', reportNo: 'BO NOVO 2/2026', authName: 'Familiar de teste', authRelation: 'familiar', authOk: true, scope: { kind: 'city' }, qr: { mode: 'off' } });
  assert.equal(novo.status, 201, JSON.stringify(novo.data));
  assert.deepEqual((await hb()).missing.map((m) => m.name), ['Caso Novo de Teste', 'Caso Antigo de Teste']);
  const cl = await A('POST', `/api/prefeitura/missing/${old.id}/close`, { reason: 'localizado' });
  assert.equal(cl.status, 200, JSON.stringify(cl.data));
  assert.deepEqual((await hb()).missing.map((m) => m.name), ['Caso Novo de Teste']);
  assert.equal((await A('GET', '/api/prefeitura/missing')).data.closed.find((m) => m.id === old.id).closeReason, 'localizado');
}
/** O 1º servidor (esquema atual) deixa uma repartição, um usuário dela e um alerta com tipo: linhas de verdade nas outras duas tabelas. */
async function prepara(s) {
  const anon = api(s.base);
  const A = api(s.base, (await anon('POST', '/api/admin/login', { password: 'senha-inicial-longa' })).data.token);
  const ubs = (await A('POST', '/api/prefeitura/offices', { name: 'UBS Antiga', type: 'ubs', lat: -22.9, lng: -43.2 })).data;
  assert.ok(ubs.id, JSON.stringify(ubs));
  assert.equal((await A('POST', `/api/prefeitura/offices/${ubs.id}/users`, { username: 'gestor.antigo', password: 'senha-do-antigo-2026' })).status, 201);
  const link = (await A('POST', `/api/prefeitura/offices/${ubs.id}/link`, {})).data.url.split('/').pop();
  const al = await A('POST', '/api/prefeitura/alerts', { category: 'saude', kind: 'surto', title: 'Alerta antigo', level: 'warn', durationMin: 600, scope: { kind: 'city' } });
  assert.equal(al.status, 201, JSON.stringify(al.data));
  return { ubsId: ubs.id, userLogin: { token: link, username: 'gestor.antigo', password: 'senha-do-antigo-2026' }, alertId: al.data.alert.id };
}

test('SQLite: banco com telas_missing da 0.5.188 e linhas antigas; o esquema atual sobe por cima sem perder nada', { timeout: 300000 }, async () => {
  let s = await boot({ TELAS_LINK_LOGIN_PER_IP: '100', PLATFORM_PUBLIC_URL: 'https://painel.exemplo.test' });
  const dataDir = s.dataDir;
  try {
    const ctx = await prepara(s);
    await s.stop();
    // volta a tabela ao que a 0.5.188 criou, com uma linha daquela época
    const db = new DatabaseSync(path.join(dataDir, 'playout.db'), { timeout: 15000 });
    db.exec('DROP TABLE telas_missing'); db.exec(missing0588('sqlite')); db.exec(OLD_ROW(Date.now() + 5 * 86400e3, Date.now() - 86400e3));
    const cols = () => db.prepare('PRAGMA table_info(telas_missing)').all().map((c) => c.name);
    for (const c of NEW_COLS) assert.ok(!cols().includes(c), `antes: sem ${c}`);
    assert.deepEqual([db.prepare('SELECT COUNT(*) AS n FROM telas_office_users').get().n, db.prepare('SELECT COUNT(*) AS n FROM telas_alert_info').get().n], [1, 1]);
    db.close();
    s = await boot({ DATA_DIR: dataDir, TELAS_LINK_LOGIN_PER_IP: '100', PLATFORM_PUBLIC_URL: 'https://painel.exemplo.test' });
    const after = new DatabaseSync(path.join(dataDir, 'playout.db'), { timeout: 15000 });
    const now = after.prepare('PRAGMA table_info(telas_missing)').all();
    for (const c of NEW_COLS) assert.ok(now.some((x) => x.name === c), `depois: ${c} existe`);
    assert.deepEqual(after.prepare('SELECT name, qr_mode, qr_data, header, warrant_no FROM telas_missing').all().map((r) => ({ ...r })), [{ name: 'Caso Antigo de Teste', qr_mode: 'default', qr_data: null, header: null, warrant_no: null }], 'a linha antiga fica, com o padrão nas colunas novas');
    after.close();
    await confere(s, ctx);
    // subir de novo não muda nada (idempotente)
    await s.stop(); s = await boot({ DATA_DIR: dataDir, TELAS_LINK_LOGIN_PER_IP: '100', PLATFORM_PUBLIC_URL: 'https://painel.exemplo.test' });
    assert.equal((await api(s.base)('GET', '/healthz')).status, 200);
  } finally { await s.stop(); cleanup(dataDir); }
});

test('Postgres: a mesma migração (ALTER TABLE … ADD COLUMN IF NOT EXISTS) com as linhas antigas no lugar', { timeout: 300000 }, async (t) => {
  const { startPg } = await import('./helpers/pg.js');
  const { createPg } = await import('../server/db/pg.js');
  let pgs;
  try { pgs = await startPg(); } catch (err) { t.skip(`Postgres embutido indisponível: ${err.message}`); return; }
  let s = null; let db = null; const env = { DATABASE_URL: pgs.url, TELAS_LINK_LOGIN_PER_IP: '100', PLATFORM_PUBLIC_URL: 'https://painel.exemplo.test' };
  try {
    s = await boot(env);
    const dataDir = s.dataDir;
    const ctx = await prepara(s);
    await s.stop();
    db = await createPg(pgs.url, { max: 2 });
    await db.exec('DROP TABLE telas_missing'); await db.exec(missing0588('pg')); await db.exec(OLD_ROW(Date.now() + 5 * 86400e3, Date.now() - 86400e3));
    const cols = async () => (await db.all("SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns WHERE table_name = 'telas_missing'"));
    for (const c of NEW_COLS) assert.ok(!(await cols()).some((x) => x.column_name === c), `antes: sem ${c}`);
    const before = await cols();
    await db.close(); db = null;
    s = await boot({ ...env, DATA_DIR: dataDir });
    db = await createPg(pgs.url, { max: 2 });
    const now = await cols();
    for (const c of NEW_COLS) assert.ok(now.some((x) => x.column_name === c), `depois: ${c} existe`);
    const qr = now.find((x) => x.column_name === 'qr_mode');
    assert.deepEqual([qr.data_type, qr.is_nullable], ['text', 'NO']); assert.match(qr.column_default, /default/);
    // nenhuma coluna de antes mudou de tipo nem de NOT NULL
    for (const b of before) { const n = now.find((x) => x.column_name === b.column_name); assert.deepEqual([n.data_type, n.is_nullable], [b.data_type, b.is_nullable], b.column_name); }
    const rows = await db.all('SELECT name, qr_mode, qr_data, header, warrant_no FROM telas_missing');
    assert.deepEqual(rows.map((r) => ({ ...r })), [{ name: 'Caso Antigo de Teste', qr_mode: 'default', qr_data: null, header: null, warrant_no: null }]);
    await confere(s, ctx);
  } finally {
    if (db) await db.close().catch(() => {});
    if (s) { await s.stop(); cleanup(s.dataDir); }
    await pgs.stop().catch(() => {});
  }
});
