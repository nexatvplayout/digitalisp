/**
 * NEXA Telas · TV Corporativa, pacote A (docs/TV-CORPORATIVA.md §3.1): conteúdo, grade e exibição. Escrito uma vez para os
 * dois dialetos (como schema-telas.js). Só tabelas novas, CREATE TABLE/INDEX IF NOT EXISTS, sem chave estrangeira, tenant_id
 * em toda tabela. Tempos em epoch ms; dias em AAAA-MM-DD do fuso da empresa; JSON em TEXT.
 *   - tvcorp_settings: uma linha por cliente (data: logomarca, tema, fuso, aprovação, grade padrão, datas comemorativas).
 *   - tvcorp_media: a biblioteca (imagem enviada, já preparada em graphics/tvcmedia-<uuid>.jpg, ou slide de modelo).
 *   - tvcorp_playlists e tvcorp_playlist_items: as sequências, com tempo, validade, dias e faixa de horário por item.
 *   - tvcorp_layouts: os layouts por zonas (copiados de um modelo de fábrica e ajustados).
 *   - tvcorp_schedules: a grade (layout + playlist de cada zona + alcance + dias, horário, período e prioridade).
 *   - tvcorp_plays e tvcorp_hours: o relatório de exibição e as horas em exibição por tela e dia (400 dias).
 */
export function tvcorpDDL(d) {
  const id = d === 'pg' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const big = d === 'pg' ? 'BIGINT' : 'INTEGER';
  return `
CREATE TABLE IF NOT EXISTS tvcorp_settings (
  tenant_id   ${big} PRIMARY KEY,
  data        TEXT NOT NULL DEFAULT '{}',
  updated_at  ${big}
);
CREATE TABLE IF NOT EXISTS tvcorp_media (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  office_id   ${big},
  kind        TEXT NOT NULL,
  title       TEXT NOT NULL DEFAULT '',
  file        TEXT,
  sha256      TEXT,
  bytes       ${big},
  width       INTEGER,
  height      INTEGER,
  template    TEXT,
  fields      TEXT NOT NULL DEFAULT '{}',
  seconds     INTEGER NOT NULL DEFAULT 10,
  status      TEXT NOT NULL DEFAULT 'ok',
  created_by  TEXT NOT NULL DEFAULT '',
  created_at  ${big} NOT NULL,
  updated_at  ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_media_tenant ON tvcorp_media(tenant_id, id);
CREATE TABLE IF NOT EXISTS tvcorp_playlists (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  office_id   ${big},
  name        TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  shuffle     INTEGER NOT NULL DEFAULT 0,
  sort        INTEGER NOT NULL DEFAULT 0,
  created_at  ${big} NOT NULL,
  updated_at  ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_playlists_tenant ON tvcorp_playlists(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_playlist_items (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  playlist_id ${big} NOT NULL,
  ref_kind    TEXT NOT NULL,
  ref_id      ${big},
  params      TEXT NOT NULL DEFAULT '{}',
  seconds     INTEGER NOT NULL DEFAULT 10,
  sort        INTEGER NOT NULL DEFAULT 0,
  valid_from  TEXT,
  valid_to    TEXT,
  days        TEXT NOT NULL DEFAULT '',
  time_from   INTEGER,
  time_to     INTEGER
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_items_playlist ON tvcorp_playlist_items(tenant_id, playlist_id, sort);
CREATE INDEX IF NOT EXISTS idx_tvcorp_items_ref ON tvcorp_playlist_items(tenant_id, ref_kind, ref_id);
CREATE TABLE IF NOT EXISTS tvcorp_layouts (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  name        TEXT NOT NULL,
  orientation TEXT NOT NULL DEFAULT 'land',
  zones       TEXT NOT NULL DEFAULT '[]',
  background  TEXT,
  factory_key TEXT,
  created_at  ${big} NOT NULL,
  updated_at  ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_layouts_tenant ON tvcorp_layouts(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_schedules (
  id             ${id},
  tenant_id      ${big} NOT NULL,
  name           TEXT NOT NULL,
  layout_id      ${big} NOT NULL,
  zone_playlists TEXT NOT NULL DEFAULT '{}',
  scope          TEXT NOT NULL DEFAULT 'all',
  scope_data     TEXT NOT NULL DEFAULT '{}',
  days           TEXT NOT NULL DEFAULT '',
  time_from      INTEGER NOT NULL DEFAULT 0,
  time_to        INTEGER NOT NULL DEFAULT 1440,
  date_from      TEXT,
  date_to        TEXT,
  priority       INTEGER NOT NULL DEFAULT 0,
  status         TEXT NOT NULL DEFAULT 'ok',
  created_by     TEXT NOT NULL DEFAULT '',
  created_at     ${big} NOT NULL,
  updated_at     ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_schedules_tenant ON tvcorp_schedules(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_plays (
  tenant_id   ${big} NOT NULL,
  device_id   ${big} NOT NULL,
  day         TEXT NOT NULL,
  ref_kind    TEXT NOT NULL,
  ref_id      ${big} NOT NULL DEFAULT 0,
  plays       ${big} NOT NULL DEFAULT 0,
  seconds     ${big} NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tvcorp_plays_key ON tvcorp_plays(tenant_id, device_id, day, ref_kind, ref_id);
CREATE INDEX IF NOT EXISTS idx_tvcorp_plays_day ON tvcorp_plays(tenant_id, day);
CREATE TABLE IF NOT EXISTS tvcorp_hours (
  tenant_id   ${big} NOT NULL,
  device_id   ${big} NOT NULL,
  day         TEXT NOT NULL,
  on_sec      ${big} NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tvcorp_hours_key ON tvcorp_hours(tenant_id, device_id, day);
CREATE INDEX IF NOT EXISTS idx_tvcorp_hours_day ON tvcorp_hours(tenant_id, day);
`;
}

/** Todas as tabelas do pacote A: entram em TELAS_TABLES (a exclusão do cliente apaga as linhas de cada uma). */
export const TVCORP_TABLES = Object.freeze(['tvcorp_settings', 'tvcorp_media', 'tvcorp_playlists', 'tvcorp_playlist_items', 'tvcorp_layouts', 'tvcorp_schedules', 'tvcorp_plays', 'tvcorp_hours']);
/** Cópia SQLite -> Postgres (TELAS_COPY): a mesma lista. */
export const TVCORP_COPY = TVCORP_TABLES;
/** Tabelas com identidade (TELAS_IDENTITY). */
export const TVCORP_IDENTITY = Object.freeze(['tvcorp_media', 'tvcorp_playlists', 'tvcorp_playlist_items', 'tvcorp_layouts', 'tvcorp_schedules']);
