/**
 * NEXA Telas, o modo prefeitura (server/telas.js, docs/TELAS.md): a rede de TV box das repartições, escrita uma vez para os
 * dois dialetos (como schema-curtidas.js). Só aditivo e idempotente (CREATE TABLE/INDEX IF NOT EXISTS), sem coluna nova em
 * tabela antiga e sem chave estrangeira (como o resto do esquema). Toda tabela leva tenant_id e toda consulta filtra por ele.
 * Segredos: só o SHA-256 do token do aparelho, da chave de acesso e do link de controle; a senha do link em scrypt; do PIN,
 * só o sal e o hash (dentro do JSON de config). Nada disso volta por nenhuma rota.
 *   - telas_regions: bairros e distritos (nome e cor).
 *   - telas_offices: repartições (tipo do catálogo public/shared/telas-tipos.js, endereço, ponto no mapa, região, responsável,
 *     módulos e config em JSON, canal; link de controle: link_hash, link_pass e link_ver, que sobe a cada troca e derruba as
 *     sessões abertas).
 *   - telas_devices: as telas (TV box). token_hash NULL = revogada. O estado do último sinal de vida fica na própria linha;
 *     online_since = desde quando está ligada sem parar; shot_at = a hora da última captura (o JPEG fica em DATA_DIR/telas).
 *   - telas_groups: grupos de telas. office_type NULL = manual (as telas em telas_group_devices); com o tipo = automático
 *     (todas as telas das repartições daquele tipo, sem linha de vínculo). config em JSON: avisos e layout do grupo.
 *   - telas_keys: chaves de acesso de uso único (24 h), ligadas a uma repartição.
 *   - telas_commands: a fila de comandos de cada tela (entregue uma vez no sinal de vida).
 *   - telas_alerts: os alertas (alcance em scope + scope_data JSON) e telas_alert_deliveries: as telas que receberam cada um.
 */
