/**
 * Fases 3 e 4 (docs/TELAS.md, contrato §7): tabelas novas, nenhuma coluna em tabela de antes.
 *   - telas_office_extras: o que a repartição ganhou depois (uma linha por repartição): data em JSON (a configuração da
 *     chamada de senha) e o token do totem (só o SHA-256; totem_at = quando foi gerado).
 *   - telas_queue_services: as filas (serviços) da repartição: nome, letra(s) da senha e se aceita prioridade.
 *   - telas_queue_tickets: as senhas. day = o dia em America/Sao_Paulo (a numeração recomeça a cada dia: única por
 *     repartição, dia e código); priority 0 normal, 1 prioritária, 2 = 80+; risk = a cor da classificação (UPA, hospital);
 *     name = já reduzido (primeiro nome + inicial; o nome inteiro nunca é guardado). queued_at = quando entrou na fila em que
 *     está (encaminhar muda); first_called_at e done_at para o relatório. Guardadas 90 dias.
 *   - telas_queue_calls: cada chamada (o id dela é o "id" do contrato §7.2; repetir não cria outra: repeats sobe e shown_at
 *     passa a ser a hora da repetição; at fica com a hora da primeira).
 *   - telas_cards: os cartões de informação (tipo, título, linhas em JSON, dia da semana ou período, ordem, classificação).
 *   - telas_approvals: a fila da SECOM (o que a repartição pediu pelo link de controle: avisos, cartão ou alerta em JSON),
 *     quem pediu, quem decidiu e quando. status: pending, approved, rejected, superseded, auto (Defesa Civil: saiu na hora).
 *   - telas_alert_meta: a classificação do alerta (modo eleitoral) e a marca "sem aprovação".
 *   - telas_offline: os vídeos guardados escolhidos por nível (default, group, office) e telas_media_hashes: o SHA-256 de
 *     cada vídeo, calculado uma vez em segundo plano (vale enquanto o arquivo e o tamanho forem os mesmos).
 *   - telas_device_events: as mudanças de situação de cada tela (on, warn, off), para o "desligada há X" e a disponibilidade.
 *   - telas_municipio: o município da prefeitura (uma linha por cliente): código do IBGE, nome e UF, e o contorno buscado na
 *     malha do IBGE (server/telas-malha.js): a caixa envolvente, os polígonos simplificados em JSON, quando veio e o erro da
 *     última tentativa. Sem contorno (o IBGE falhou), o município fica guardado assim mesmo e o painel tenta de novo.
 *   - telas_office_users: os usuários do painel da repartição (/reparticao/<link>): username único dentro da repartição
 *     (guardado em minúsculas), nome, a senha em scrypt (pass), o papel (gestor ou atendente) e se está ativo. ver sobe a
 *     cada troca de senha, de papel ou de situação e derruba as sessões abertas daquele usuário.
 *   - telas_panic: os acionamentos do botão de pânico (aviso silencioso de uma repartição à Segurança: nunca vai a tela
 *     nenhuma): quem acionou e quando, quem recebeu e quando, quem encerrou e a nota. Guardados 90 dias.
 *   - telas_api_keys: a chave de integração de um emissor conveniado (só o SHA-256; a data do último uso).
 *   - telas_guiche: o endereço do guichê de cada repartição (/reparticao/<token>/guiche): só o SHA-256 do token; gerar
 *     outro troca a linha e derruba o anterior.
 *   - telas_alert_info: a categoria, o tipo e a marca de teste do alerta, e a linha de cima (header) montada ao criar
 *     (contrato §9). Tabela à parte, como telas_alert_meta: alerta sem linha aqui é um alerta de antes, sem nada disso.
 *   - telas_missing: os casos de pessoa desaparecida (contrato §8): os dados que vão à tela, a foto (o nome do arquivo no
 *     armazenamento, o SHA-256 e o tamanho; apagada ao encerrar), como mostrar, o alcance (o mesmo dos alertas), a validade
 *     e a situação. report_no, auth_name, auth_relation e auth_ok são a autorização da divulgação: NUNCA vão ao aparelho
 *     nem a rota pública. Encerrado há mais de 90 dias, o registro sai na limpeza.
 *   - telas_offline_image (14/11, tabela nova: migração aditiva pelo CREATE TABLE IF NOT EXISTS): a imagem de reserva sem
 *     conexão (contrato offline.image) de cada nível (default/0, group, office), uma por nível: o arquivo no armazenamento
 *     ("telasimg-<uuid>.jpg", JPEG 1920×1080 até 2 MB), o SHA-256 e o tamanho (server/telas-imagem-offline.js).
 *   UPA (19/11, docs/TELAS.md §26 a §31; tabelas novas, migração aditiva pelo CREATE TABLE IF NOT EXISTS, nenhuma coluna
 *   nova em tabela de antes):
 *   - telas_room_groups: os grupos de salas (nome, as filas que atendem em JSON, o automático em round robin).
 *   - telas_rooms: as salas e consultórios (nome, tipo, grupo, ativa, a situação Disponível/Pausa/Ocupada, desde quando
 *     e a senha que está nela).
 *   - telas_access: os endereços próprios sem login (kind 'sala' com ref_id = a sala; 'apoio' com ref_id 0): só o SHA-256;
 *     gerar outro troca a linha.
 *   - telas_support: os pedidos de apoio das salas (o que, de que sala, quem aceitou, quando). 90 dias.
 *   - telas_queue_events: a linha do tempo da senha para os indicadores (a cor dada e cada chamada com a sala e o tipo
 *     dela). Só a cor do risco; nunca o motivo. 90 dias.
 *   - telas_follow: o QR do acompanhante (o SHA-256 do token opaco e o fim do dia em que vence).
 */
