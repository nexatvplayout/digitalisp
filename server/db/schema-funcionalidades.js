/**
 * Funcionalidades por plano (docs/PLATAFORMA.md, "Funcionalidades por plano"; server/funcionalidades.js): o que o catálogo
 * acrescenta ao banco, escrito uma vez para os dois dialetos (como schema-classind.js). Só aditivo e idempotente:
 *   - feature_profiles: os perfis de funcionalidades do Superadmin (nome, descrição e o conjunto { chave: boolean } do
 *     catálogo public/shared/funcionalidades.js, em JSON). Sem chave estrangeira (como o resto do esquema).
 *   - plans.profile_id (coluna nova, NULL = funcionalidades próprias do plano): o perfil que o plano usa. Entra pela migração
 *     de cada driver (sqlite.js addCol; pgMigrate ALTER TABLE ... ADD COLUMN IF NOT EXISTS), nunca reescrevendo um plano.
 */
export function funcionalidadesDDL(d) {
  const id = d === 'pg' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const big = d === 'pg' ? 'BIGINT' : 'INTEGER';
  return `
CREATE TABLE IF NOT EXISTS feature_profiles (
  id          ${id},
  code        TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  features    TEXT NOT NULL DEFAULT '{}',
  sort        INTEGER NOT NULL DEFAULT 0,
  created_at  ${big} NOT NULL,
  updated_at  ${big}
);
`;
}
/** A coluna nova em plans, para o pgMigrate (o SQLite acrescenta em sqlite.js, addCol). */
export const FUNCIONALIDADES_PG_MIGRATE = 'ALTER TABLE plans         ADD COLUMN IF NOT EXISTS profile_id BIGINT;';
export const FUNCIONALIDADES_COPY = ['feature_profiles'];
export const FUNCIONALIDADES_IDENTITY = ['feature_profiles'];
