/**
 * TV Corporativa, pacote B (docs/TV-CORPORATIVA.md §3.2): fontes de dados, RH, indicadores, widgets e o celular do
 * funcionário (server/tvcorp-dados.js). Escrito uma vez para os dois dialetos, como schema-telas.js: só aditivo e
 * idempotente (CREATE TABLE/INDEX IF NOT EXISTS), sem coluna nova em tabela antiga e sem chave estrangeira. Toda tabela
 * leva tenant_id e toda consulta filtra por ele. Tempos em epoch ms; dias em 'AAAA-MM-DD' (America/Sao_Paulo).
 *   - tvcorp_feeds: as fontes (rss, quotes, weather, traffic). config em JSON; cache = os itens já limpos da última busca boa
 *     (fetched_at); tried_at = a última tentativa (certa ou errada); last_error = o erro da última, ou NULL.
 *   - tvcorp_people: aniversariantes e admissões. SÓ dia e mês do aniversário (não existe coluna de ano). photo só com
 *     photo_consent = 1 (desmarcar apaga o arquivo na hora); photo_sha e photo_bytes para o app conferir o arquivo.
 *   - tvcorp_posts: os comunicados (categoria, validade, alcance como os alertas, "Li", aprovação).
 *   - tvcorp_post_acks: quem tocou em "Li" (o nome ou a matrícula que a pessoa escreveu; who_key = a forma comparável).
 *   - tvcorp_kpis e tvcorp_kpi_points: os indicadores e a série para o gráfico (400 dias).
 *   - tvcorp_widgets: contador, dias sem acidente, relógio mundial e cardápio (data em JSON).
 *   - tvcorp_mobile: o endereço do celular (/tvc/<token>): só o SHA-256 do token; revoked_at = desligado.
 *   - tvcorp_suggestions: o que veio do celular (sugestão, conteúdo, pesquisa); o IP nunca é guardado. 180 dias.
 */
export function tvcorpDadosDDL(d) {
  const id = d === 'pg' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const big = d === 'pg' ? 'BIGINT' : 'INTEGER';
  const real = d === 'pg' ? 'DOUBLE PRECISION' : 'REAL';
  return `
CREATE TABLE IF NOT EXISTS tvcorp_feeds (
  id           ${id},
  tenant_id    ${big} NOT NULL,
  kind         TEXT NOT NULL,
  name         TEXT NOT NULL,
  config       TEXT NOT NULL DEFAULT '{}',
  refresh_min  INTEGER NOT NULL DEFAULT 30,
  cache        TEXT,
  fetched_at   ${big},
  tried_at     ${big},
  last_error   TEXT,
  enabled      INTEGER NOT NULL DEFAULT 1,
  created_at   ${big} NOT NULL,
  updated_at   ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_feeds_tenant ON tvcorp_feeds(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_people (
  id             ${id},
  tenant_id      ${big} NOT NULL,
  office_id      ${big},
  name           TEXT NOT NULL,
  sector         TEXT NOT NULL DEFAULT '',
  bday_day       INTEGER,
  bday_month     INTEGER,
  hire_date      TEXT,
  photo          TEXT,
  photo_sha      TEXT,
  photo_bytes    INTEGER,
  photo_consent  INTEGER NOT NULL DEFAULT 0,
  active         INTEGER NOT NULL DEFAULT 1,
  created_at     ${big} NOT NULL,
  updated_at     ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_people_tenant ON tvcorp_people(tenant_id, office_id);
CREATE INDEX IF NOT EXISTS idx_tvcorp_people_bday ON tvcorp_people(tenant_id, bday_month, bday_day);
CREATE TABLE IF NOT EXISTS tvcorp_posts (
  id           ${id},
  tenant_id    ${big} NOT NULL,
  office_id    ${big},
  category     TEXT NOT NULL DEFAULT 'comunicado',
  title        TEXT NOT NULL,
  body         TEXT NOT NULL DEFAULT '',
  media_id     ${big},
  qr_url       TEXT,
  scope        TEXT NOT NULL DEFAULT 'all',
  scope_data   TEXT NOT NULL DEFAULT '{}',
  valid_from   ${big},
  valid_to     ${big},
  needs_ack    INTEGER NOT NULL DEFAULT 0,
  status       TEXT NOT NULL DEFAULT 'ok',
  reason       TEXT,
  created_by   TEXT NOT NULL DEFAULT '',
  created_via  TEXT NOT NULL DEFAULT 'painel',
  decided_by   TEXT,
  decided_at   ${big},
  created_at   ${big} NOT NULL,
  updated_at   ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_posts_tenant ON tvcorp_posts(tenant_id, status);
CREATE TABLE IF NOT EXISTS tvcorp_post_acks (
  tenant_id  ${big} NOT NULL,
  post_id    ${big} NOT NULL,
  who        TEXT NOT NULL,
  who_key    TEXT NOT NULL,
  at         ${big} NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tvcorp_post_acks_who ON tvcorp_post_acks(post_id, who_key);
CREATE INDEX IF NOT EXISTS idx_tvcorp_post_acks_tenant ON tvcorp_post_acks(tenant_id, post_id);
CREATE TABLE IF NOT EXISTS tvcorp_kpis (
  id           ${id},
  tenant_id    ${big} NOT NULL,
  office_id    ${big},
  name         TEXT NOT NULL,
  unit         TEXT NOT NULL DEFAULT '',
  value        ${real},
  target       ${real},
  direction    TEXT NOT NULL DEFAULT 'up',
  bands        TEXT NOT NULL DEFAULT '[]',
  source       TEXT NOT NULL DEFAULT 'manual',
  source_cfg   TEXT NOT NULL DEFAULT '{}',
  refresh_min  INTEGER NOT NULL DEFAULT 60,
  tried_at     ${big},
  created_at   ${big} NOT NULL,
  updated_at   ${big},
  last_error   TEXT
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_kpis_tenant ON tvcorp_kpis(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_kpi_points (
  tenant_id  ${big} NOT NULL,
  kpi_id     ${big} NOT NULL,
  at         ${big} NOT NULL,
  value      ${real} NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_kpi_points ON tvcorp_kpi_points(tenant_id, kpi_id, at);
CREATE TABLE IF NOT EXISTS tvcorp_widgets (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  kind        TEXT NOT NULL,
  name        TEXT NOT NULL,
  data        TEXT NOT NULL DEFAULT '{}',
  created_at  ${big} NOT NULL,
  updated_at  ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_widgets_tenant ON tvcorp_widgets(tenant_id);
CREATE TABLE IF NOT EXISTS tvcorp_mobile (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  office_id   ${big},
  token_hash  TEXT,
  name        TEXT NOT NULL DEFAULT '',
  created_by  TEXT NOT NULL DEFAULT '',
  created_at  ${big} NOT NULL,
  revoked_at  ${big}
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_mobile_tenant ON tvcorp_mobile(tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tvcorp_mobile_token ON tvcorp_mobile(token_hash);
CREATE TABLE IF NOT EXISTS tvcorp_suggestions (
  id          ${id},
  tenant_id   ${big} NOT NULL,
  office_id   ${big},
  mobile_id   ${big},
  kind        TEXT NOT NULL DEFAULT 'sugestao',
  text        TEXT NOT NULL DEFAULT '',
  media_file  TEXT,
  who         TEXT NOT NULL DEFAULT '',
  status      TEXT NOT NULL DEFAULT 'pending',
  reason      TEXT,
  decided_by  TEXT,
  decided_at  ${big},
  created_at  ${big} NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tvcorp_suggestions_tenant ON tvcorp_suggestions(tenant_id, status);
`;
}

