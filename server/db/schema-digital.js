// Tabelas próprias do DIGITAL ISP. Só mudanças aditivas (banco de produção): tabela nova ou coluna nova, nunca apagar.
//   isp_revenda    dados completos da revenda além de tenants (nome fantasia, WhatsApp, responsável, município do IBGE,
//                  ponto no mapa) e como ela é cobrada (pelo sistema ou por fora, dia do vencimento, valor combinado)
//   isp_faturas    as cobranças mensais da plataforma para cada revenda (abertas, pagas, canceladas), geradas pelo sistema
//                  ou lançadas à mão; o pagamento por fora é registrado aqui
export function digitalDDL(d) {
  const id = d === 'pg' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const big = d === 'pg' ? 'BIGINT' : 'INTEGER';
  const real = d === 'pg' ? 'DOUBLE PRECISION' : 'REAL';
  return `
CREATE TABLE IF NOT EXISTS isp_revenda (
  tenant_id      ${big} PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  fantasia       TEXT NOT NULL DEFAULT '',
  whatsapp       TEXT NOT NULL DEFAULT '',
  responsavel    TEXT NOT NULL DEFAULT '',
  resp_cpf       TEXT NOT NULL DEFAULT '',
  site           TEXT NOT NULL DEFAULT '',
  uf             TEXT NOT NULL DEFAULT '',
  municipio      TEXT NOT NULL DEFAULT '',
  municipio_ibge ${big},
  lat            ${real},
  lng            ${real},
  cobranca_modo  TEXT NOT NULL DEFAULT 'fora',
  dia_vencimento INTEGER NOT NULL DEFAULT 10,
  valor_cents    ${big},
  updated_at     ${big} NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS isp_faturas (
  id             ${id},
  tenant_id      ${big} NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  referencia     TEXT NOT NULL,
  descricao      TEXT NOT NULL DEFAULT '',
  valor_cents    ${big} NOT NULL,
  vencimento     TEXT NOT NULL,
  status         TEXT NOT NULL DEFAULT 'aberta',
  modo           TEXT NOT NULL DEFAULT 'fora',
  pago_em        ${big},
  pago_valor_cents ${big},
  pago_forma     TEXT,
  obs            TEXT NOT NULL DEFAULT '',
  gateway_id     TEXT,
  link           TEXT,
  created_at     ${big} NOT NULL,
  created_by     TEXT NOT NULL DEFAULT ''
);
-- a biblioteca de vídeos do NEXA, que o módulo das telas ainda consulta (vídeos guardados para a tela sem internet):
-- tabela mínima e vazia, só para a consulta não falhar; os vídeos do DIGITAL ISP ficam em tvcorp_media
CREATE TABLE IF NOT EXISTS media (
  id        ${id},
  tenant_id ${big} NOT NULL,
  title     TEXT NOT NULL DEFAULT '',
  filename  TEXT NOT NULL DEFAULT '',
  size      ${big} NOT NULL DEFAULT 0,
  duration  ${real} NOT NULL DEFAULT 0,
  kind      TEXT NOT NULL DEFAULT 'program',
  status    TEXT NOT NULL DEFAULT 'ready',
  censura   INTEGER NOT NULL DEFAULT 0
);
-- endereço estruturado do cliente final (unidade): o texto, a latitude e a longitude seguem em telas_offices
CREATE TABLE IF NOT EXISTS isp_unidade_endereco (
  office_id      ${big} PRIMARY KEY REFERENCES telas_offices(id) ON DELETE CASCADE,
  tenant_id      ${big} NOT NULL,
  cep            TEXT NOT NULL DEFAULT '',
  rua            TEXT NOT NULL DEFAULT '',
  numero         TEXT NOT NULL DEFAULT '',
  complemento    TEXT NOT NULL DEFAULT '',
  bairro         TEXT NOT NULL DEFAULT '',
  uf             TEXT NOT NULL DEFAULT '',
  municipio      TEXT NOT NULL DEFAULT '',
  municipio_ibge ${big},
  precisao       TEXT,
  updated_at     ${big} NOT NULL DEFAULT 0
);
-- conta: a revenda (o provedor) ou o cliente final dela (uma conta própria, filha da revenda; telas e conteúdo ficam
-- separados por conta). Conta sem linha aqui é revenda (as que já existiam)
CREATE TABLE IF NOT EXISTS isp_conta (
  tenant_id        ${big} PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  tipo             TEXT NOT NULL DEFAULT 'revenda',
  revenda_id       ${big},
  pessoa           TEXT NOT NULL DEFAULT 'pj',
  plano_cliente_id ${big},
  created_at       ${big} NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS isp_conta_revenda ON isp_conta(revenda_id);
-- os planos que a revenda cria para os clientes dela (dentro do plano dela com a plataforma)
CREATE TABLE IF NOT EXISTS isp_planos_cliente (
  id          ${id},
  revenda_id  ${big} NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  nome        TEXT NOT NULL,
  descricao   TEXT NOT NULL DEFAULT '',
  telas       INTEGER,
  usuarios    INTEGER,
  storage_mb  INTEGER,
  modulos     TEXT NOT NULL DEFAULT '{}',
  preco_cents ${big} NOT NULL DEFAULT 0,
  ativo       INTEGER NOT NULL DEFAULT 1,
  sort        INTEGER NOT NULL DEFAULT 0,
  created_at  ${big} NOT NULL
);
-- as cobranças da revenda para os clientes dela
CREATE TABLE IF NOT EXISTS isp_faturas_cliente (
  id               ${id},
  revenda_id       ${big} NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  cliente_id       ${big} NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  referencia       TEXT NOT NULL,
  descricao        TEXT NOT NULL DEFAULT '',
  valor_cents      ${big} NOT NULL,
  vencimento       TEXT NOT NULL,
  status           TEXT NOT NULL DEFAULT 'aberta',
  modo             TEXT NOT NULL DEFAULT 'fora',
  pago_em          ${big},
  pago_valor_cents ${big},
  pago_forma       TEXT,
  obs              TEXT NOT NULL DEFAULT '',
  gateway_id       TEXT,
  link             TEXT,
  created_at       ${big} NOT NULL,
  created_by       TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS isp_faturas_cliente_ref ON isp_faturas_cliente(cliente_id, referencia);
CREATE INDEX IF NOT EXISTS isp_faturas_cliente_rev ON isp_faturas_cliente(revenda_id, status, vencimento);
-- "esqueci minha senha" (server/senha-recuperar.js): só o hash do código do link; vale 30 min, uma vez
CREATE TABLE IF NOT EXISTS isp_senha_reset (
  id         ${id},
  user_id    ${big} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at ${big} NOT NULL,
  used_at    ${big},
  created_at ${big} NOT NULL,
  ip         TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS isp_senha_reset_user ON isp_senha_reset(user_id);
-- canais ao vivo (HLS) da conta; a unidade escolhe um em telas_offices.channel_id
CREATE TABLE IF NOT EXISTS isp_hls (
  id         ${id},
  tenant_id  ${big} NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  nome       TEXT NOT NULL,
  url        TEXT NOT NULL,
  ativo      INTEGER NOT NULL DEFAULT 1,
  created_at ${big} NOT NULL
);
CREATE INDEX IF NOT EXISTS isp_hls_tenant ON isp_hls(tenant_id);
-- o gerenciador de QR code (server/qrcodes.js): o QR dinâmico e as leituras por dia (sem guardar quem leu)
CREATE TABLE IF NOT EXISTS isp_qr (
  id             ${id},
  tenant_id      ${big} NOT NULL,
  codigo         TEXT NOT NULL UNIQUE,
  nome           TEXT NOT NULL DEFAULT '',
  tipo           TEXT NOT NULL DEFAULT 'link',
  alvo           TEXT NOT NULL,
  estilo         TEXT NOT NULL DEFAULT '{}',
  ativo          INTEGER NOT NULL DEFAULT 1,
  leituras       ${big} NOT NULL DEFAULT 0,
  ultima_leitura ${big},
  criado_em      ${big} NOT NULL,
  atualizado_em  ${big}
);
CREATE INDEX IF NOT EXISTS isp_qr_tenant ON isp_qr(tenant_id);
CREATE TABLE IF NOT EXISTS isp_qr_dias (
  qr_id  ${big} NOT NULL,
  dia    TEXT NOT NULL,
  n      INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (qr_id, dia)
);
-- os registros de DNS e o estado de um domínio próprio (server/dominios.js), como o Cloudflare devolveu
CREATE TABLE IF NOT EXISTS isp_dominio_dns (
  domain_id  ${big} PRIMARY KEY,
  records    TEXT NOT NULL DEFAULT '{}'
);
-- a rádio de fundo de um layout sem vídeo (server/radios.js; a lista em server/radios-br.json)
CREATE TABLE IF NOT EXISTS isp_layout_radio (
  layout_id  ${big} PRIMARY KEY REFERENCES tvcorp_layouts(id) ON DELETE CASCADE,
  tenant_id  ${big} NOT NULL,
  station    TEXT NOT NULL,
  volume     INTEGER NOT NULL DEFAULT 100
);
-- o canal ao vivo de UMA tela (vence o da unidade)
CREATE TABLE IF NOT EXISTS isp_tela_hls (
  device_id  ${big} PRIMARY KEY REFERENCES telas_devices(id) ON DELETE CASCADE,
  tenant_id  ${big} NOT NULL,
  hls_id     ${big} NOT NULL REFERENCES isp_hls(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS isp_faturas_ref ON isp_faturas(tenant_id, referencia);
CREATE INDEX IF NOT EXISTS isp_faturas_status ON isp_faturas(status, vencimento);
-- a notícia que a empresa tirou da programação (Notícias e dados): chave = hash do link (ou do título) da manchete
CREATE TABLE IF NOT EXISTS isp_noticia_oculta (
  feed_id    ${big} NOT NULL REFERENCES tvcorp_feeds(id) ON DELETE CASCADE,
  tenant_id  ${big} NOT NULL,
  chave      TEXT NOT NULL,
  criado_em  ${big} NOT NULL,
  PRIMARY KEY (feed_id, chave)
);
`;
}
